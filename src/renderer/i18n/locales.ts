export type TranslationMap = Record<Exclude<TranslationKey, FlexibleSettingsTranslationKey>, string> & Partial<Record<FlexibleSettingsTranslationKey, string>>;

export type TranslationDictionary = Partial<Record<TranslationKey, string>>;

export const fallbackTranslations: TranslationMap = zhCN;

const loadedTranslations: Partial<Record<Locale, TranslationDictionary>> = {
  'zh-CN': zhCN,
};
const pendingTranslations: Partial<Record<Locale, Promise<TranslationDictionary>>> = {};

const localeLoaders: Record<Locale, () => Promise<TranslationDictionary>> = {
  'zh-CN': async () => zhCN,
  'zh-TW': async () => (await import('./locales/zhTW')).zhTW,
  'ja-JP': async () => (await import('./locales/jaJP')).jaJP,
  'en-US': async () => (await import('./locales/enUS')).enUS,
  'ko-KR': async () => (await import('./locales/koKR')).koKR,
};

export const getLoadedTranslations = (locale: Locale): TranslationDictionary | undefined => loadedTranslations[locale];

export const loadTranslations = (locale: Locale): Promise<TranslationDictionary> => {
  const loaded = loadedTranslations[locale];
  if (loaded) {
    return Promise.resolve(loaded);
  }

  const pending = pendingTranslations[locale];
  if (pending) {
    return pending;
  }

  const request = localeLoaders[locale]().then(
    (translations) => {
      loadedTranslations[locale] = translations;
      delete pendingTranslations[locale];
      return translations;
    },
    (error: unknown) => {
      delete pendingTranslations[locale];
      throw error;
    },
  );
  pendingTranslations[locale] = request;
  return request;
};

export const isLocale = (value: string | null): value is Locale => {
  return value === 'zh-CN' || value === 'zh-TW' || value === 'ja-JP' || value === 'en-US' || value === 'ko-KR';
};
